CREATE DATABASE IF NOT EXISTS COWORK;
CREATE SCHEMA IF NOT EXISTS COWORK.APP;
CREATE SCHEMA IF NOT EXISTS COWORK.DATA;

CREATE WAREHOUSE IF NOT EXISTS COWORK_WH
  WAREHOUSE_SIZE = 'X-SMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE;

CREATE IMAGE REPOSITORY IF NOT EXISTS COWORK.APP.IMAGES;

CREATE STAGE IF NOT EXISTS COWORK.APP.SEMANTIC_MODELS
  ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE') DIRECTORY = (ENABLE = TRUE);
CREATE STAGE IF NOT EXISTS COWORK.APP.SKILLS
  ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE') DIRECTORY = (ENABLE = TRUE);

CREATE FILE FORMAT IF NOT EXISTS COWORK.APP.TEXT_FF
  TYPE = CSV RECORD_DELIMITER = 'NONE' FIELD_DELIMITER = 'NONE';

CREATE COMPUTE POOL IF NOT EXISTS COWORK_POOL
  MIN_NODES = 1 MAX_NODES = 2
  INSTANCE_FAMILY = CPU_X64_XS
  AUTO_SUSPEND_SECS = 300 AUTO_RESUME = TRUE;

-- LLM egress (DashScope / Qwen)
CREATE OR REPLACE NETWORK RULE COWORK.APP.DASHSCOPE_RULE
  MODE = EGRESS TYPE = HOST_PORT
  VALUE_LIST = ('dashscope.aliyuncs.com:443');

CREATE OR REPLACE EXTERNAL ACCESS INTEGRATION COWORK_LLM_ACCESS
  ALLOWED_NETWORK_RULES = (COWORK.APP.DASHSCOPE_RULE)
  ENABLED = TRUE;

-- !!! Replace with your own DashScope API key before running !!!
CREATE SECRET IF NOT EXISTS COWORK.APP.COWORK_DASHSCOPE_KEY
  TYPE = GENERIC_STRING
  SECRET_STRING = '<YOUR_DASHSCOPE_API_KEY>';
