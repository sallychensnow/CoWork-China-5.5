CREATE OR REPLACE TABLE PROCUREMENT_PO (
    PO_ID INT, SUPPLIER_ID INT, MATERIAL_ID INT, MATERIAL_NAME VARCHAR,
    QUANTITY INT, UNIT_PRICE FLOAT, TOTAL_AMOUNT FLOAT,
    ORDER_DATE DATE, PROMISED_DATE DATE, ACTUAL_DELIVERY_DATE DATE,
    STATUS VARCHAR
);

INSERT INTO PROCUREMENT_PO
SELECT
    SEQ4() AS PO_ID,
    UNIFORM(1,25,RANDOM()) AS SUPPLIER_ID,
    m.MATERIAL_ID,
    m.MATERIAL_NAME,
    UNIFORM(100,5000,RANDOM()) AS QUANTITY,
    m.UNIT_PRICE,
    UNIFORM(100,5000,RANDOM()) * m.UNIT_PRICE AS TOTAL_AMOUNT,
    DATEADD('day', UNIFORM(0,460,RANDOM()), '2025-07-01')::DATE AS ORDER_DATE,
    DATEADD('day', UNIFORM(0,460,RANDOM()) + UNIFORM(7,30,RANDOM()), '2025-07-01')::DATE AS PROMISED_DATE,
    DATEADD('day', UNIFORM(0,460,RANDOM()) + UNIFORM(5,45,RANDOM()), '2025-07-01')::DATE AS ACTUAL_DELIVERY_DATE,
    CASE UNIFORM(1,10,RANDOM())
        WHEN 1 THEN '待确认' WHEN 2 THEN '生产中' WHEN 3 THEN '运输中' ELSE '已收货' END AS STATUS
FROM TABLE(GENERATOR(ROWCOUNT => 400)) g
JOIN PROCUREMENT_MATERIALS m ON m.MATERIAL_ID = UNIFORM(1,30,RANDOM());

