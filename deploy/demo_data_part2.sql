INSERT INTO MFG_WORK_ORDERS
SELECT
    SEQ4() AS WO_ID,
    l.LINE_ID,
    l.LINE_NAME,
    l.PRODUCT_TYPE,
    l.DAILY_CAPACITY AS PLANNED_QTY,
    ROUND(l.DAILY_CAPACITY * UNIFORM(80,102,RANDOM())/100.0) AS ACTUAL_QTY,
    ROUND(l.DAILY_CAPACITY * UNIFORM(80,102,RANDOM())/100.0 *
