             ELSE UNIFORM(95,100,RANDOM())/100.0 END) AS GOOD_QTY,
    CASE WHEN l.LINE_ID = 3 THEN ROUND(UNIFORM(88,96,RANDOM())/100.0, 4)
         ELSE ROUND(UNIFORM(95,100,RANDOM())/100.0, 4) END AS YIELD_RATE,
    DATEADD('day', UNIFORM(0,460,RANDOM()), '2025-07-01')::DATE AS PRODUCTION_DATE,
    CASE UNIFORM(1,3,RANDOM()) WHEN 1 THEN '早班' WHEN 2 THEN '中班' ELSE '晚班' END AS SHIFT
FROM TABLE(GENERATOR(ROWCOUNT => 600)) g
JOIN MFG_PRODUCTION_LINES l ON l.LINE_ID = UNIFORM(1,8,RANDOM());

